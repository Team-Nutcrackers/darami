export function isoDate(d: Date): string {
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** 공휴일 이름(아니면 null). 일요일은 공휴일, 토요일은 별도(isNonBusinessDay). */
export function holidayName(d: Date): string | null {
  if (d.getDay() === 0) return "일요일";
  return HOLIDAYS[isoDate(d)] ?? null;
}

/** 토요일·일요일·공휴일 — 기간 말일이 이 날이면 다음 날로 넘어간다 */
export function isNonBusinessDay(d: Date): boolean {
  return d.getDay() === 6 || holidayName(d) !== null;
}

