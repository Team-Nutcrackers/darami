def _persona_block(persona: dict) -> str:
    facts = (persona or {}).get("facts") or {}
    if not facts:
        return "[사용자 페르소나]\n(아직 파악된 사실 없음. 첫 입력에서 파악할 것.)"
    return "[사용자 페르소나]\n" + json.dumps(facts, ensure_ascii=False, indent=2)


def _board_block(playbook: dict, board) -> str:
    """현재 '할 일' 보드(절차 id·이름·상태)를 모델에 알린다. 완료 체크를 모델이 보고 판단하도록."""
    procs = {p.get("id"): p for p in playbook.get("procedures", [])}
    items = [b for b in (board or []) if isinstance(b, dict) and b.get("id")]
    if not items:
        return "[할 일 보드 현황]\n(아직 보드에 올라간 절차 없음)"
    label = {"done": "완료", "in_progress": "진행 중", "waiting": "대기"}
    status = {b["id"]: b.get("status") for b in items}
    lines = []
    for b in items:
        p = procs.get(b["id"], {})
        line = f"- {b['id']} {p.get('name') or b['id']} — {label.get(b.get('status'), b.get('status'))}"
        pre = [f"{procs.get(d, {}).get('name', d)}({label.get(status.get(d), '보드에 없음')})" for d in (p.get("dependsOn") or [])]
        if pre:
            line += " · 선행: " + ", ".join(pre)
        lines.append(line)
    return "[할 일 보드 현황]\n" + "\n".join(lines)


