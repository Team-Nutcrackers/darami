from datetime import date

_WEEKDAY_KR = ["월", "화", "수", "목", "금", "토", "일"]


def today_str() -> str:
    """LLM에 주입할 '오늘 날짜' 문자열. Solar의 parametric 날짜 추측(2024 등)을 차단한다."""
    t = date.today()
    return f"{t.isoformat()} ({_WEEKDAY_KR[t.weekday()]})"


