def _index() -> tuple[dict[str, str], dict[str, dict]]:
    """이름 → 키, 키 → 메뉴 항목(자동 추가용 출처)."""
    data = json.loads(EVENTS_PATH.read_text(encoding="utf-8"))
    events = data["events"] if isinstance(data, dict) else data
    name2key: dict[str, str] = {}
    key2item: dict[str, dict] = {}
    for k, c in catalog().items():
        name2key[k] = f"common:{k}"
        name2key.setdefault(c["name"], f"common:{k}")
        key2item[f"common:{k}"] = {"kind": "law", "event": "common", "name": c["name"], "common": k}
    for e in events:
        a = e["apis"]
        for it in a["law"]:
            if it.get("common"):
                continue
            key = f"law:{it['name']}"
            name2key.setdefault(it["name"], key)
            key2item.setdefault(key, {"kind": "law", "event": e["id"], **it})
        for kind in ("gov24", "national_welfare"):
            items = a["gov24"]["services"] if kind == "gov24" else a.get("national_welfare", [])
            for s in items:
                key = f"svc:{s['service_id']}"
                name2key.setdefault(s["name"], key)
                key2item.setdefault(key, {"kind": kind, "event": e["id"], **s})
    return name2key, key2item


def main() -> None:
    name2key, key2item = _index()

    def resolve(name: str) -> str:
        if name not in name2key:
            raise SystemExit(f"의존관계 이름이 어느 메뉴에도 없음: {name!r}")
        return name2key[name]

    edges = []
    for after, before, hard, why in EDGES:
        b = [resolve(x) for x in before] if isinstance(before, list) else resolve(before)
        edges.append({"after": resolve(after), "after_name": after, "before": b,
                      "before_names": before, "hard": bool(hard), "why": why})
    out = {"_note": "할 일 의존관계 카탈로그. sources/build_deps.py 가 생성(손으로 고치지 말 것). "
                    "after 가 before 뒤에 와야 함. hard=선행이 없으면 자동 추가(any-of 는 후보가 있을 때만 연결).",
           "edges": edges, "items": key2item}
    OUT_PATH.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"edges {len(edges)} (hard {sum(e['hard'] for e in edges)}) · items {len(key2item)} → {OUT_PATH.name}")


if __name__ == "__main__":
    main()
